# Operadores de procedencia
# El orden de procedencia de los operadores es el siguiente:
# 1. Paréntesis: ()
# 2. Exponenciación: **
# 3. Unarios +x, -x
# 4. Multiplicación, División, Módulo: *, /, %
# 5. Suma, Resta: +, -
# 6. Comparacion: ==, !=, <, <=, >, >=
# 7. Operadore logicos not, and, y or
# 8. Operadores asignacion =, +=, -=, /=, %=, //= **=

# Ejemplo de precedencia de operadores
resultado = 12 / 3 + 2 * 3 - 1 # 
