# Operadores de asignación compuesta
# son una forma de asignar un valor a una variable, o de modificar el valor de una variable existente, utilizando un operador de asignación junto con una operación aritmética.
# +=, -=, *=, /=, //=, %=, **=
a = 9
print(f"El valor inicial de a es: {a}")
# Asignación compuesta con suma
a += 5 # esto es equivalente a; a = a + 5
print(f"El valor de a después de la asignación compuesta con suma (a += 5) es: {a}")
# Asignación compuesta con resta
a -= 3 # esto es equivalente a; a = a - 3
print(f"El valor de a después de la asignación compuesta con resta (a -= 3) es: {a}")
# Asignación compuesta con multiplicación   
a *= 2 # esto es equivalente a; a = a * 2
print(f"El valor de a después de la asignación compuesta con multiplicación (a *= 2) es: {a}")
# Asignación compuesta con división
a /= 4 # esto es equivalente a; a = a / 4
print(f"El valor de a después de la asignación compuesta con división (a /= 4) es: {a}")
# Asignación compuesta con división entera
a //= 2 # esto es equivalente a; a = a // 2
print(f"El valor de a después de la asignación compuesta con división entera (a //= 2) es: {a}")
# Asignación compuesta con módulo
a %= 3 # esto es equivalente a; a = a % 3
print(f"El valor de a después de la asignación compuesta con módulo (a %= 3) es: {a}")
# Asignación compuesta con potencia
a **= 4 # esto es equivalente a; a = a ** 4
print(f"El valor de a después de la asignación compuesta con potencia (a **= 4) es: {a}")
