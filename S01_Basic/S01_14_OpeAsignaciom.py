# Operadores de asignación
# son los operadores que se utilizan para asignar un valor a una variable, o para modificar el valor de una variable existente.
# necesitan al menos un operando para funcionar, y pueden ser unarios (con un solo operando) o binarios (con dos operandos).
# =, +=, -=, *=, /=, //=, %=, **=
a = 10
print(f"El valor inicial de a es: {a}")

# Asignación simple
a = 5
print(f"El valor de a después de la asignación simple es: {a}")

# Asignación con suma
a += 3
print(f"El valor de a después de la asignación con suma es: {a}")

# Asignación con resta
a -= 2
print(f"El valor de a después de la asignación con resta es: {a}")

# Asignación con multiplicación
a *= 4
print(f"El valor de a después de la asignación con multiplicación es: {a}")

# Asignación con división
a /= 2
print(f"El valor de a después de la asignación con división es: {a}")

# Asignación con división entera
a //= 2
print(f"El valor de a después de la asignación con división entera es: {a}")

# Asignación con módulo
a %= 3
print(f"El valor de a después de la asignación con módulo es: {a}")

# Asignación con potencia
a **= 2
print(f"El valor de a después de la asignación con potencia es: {a}")
